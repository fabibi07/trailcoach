def test_historical_range_and_date_filter(account, fit_dir):
    write_fit(fit_dir, "1.fit", SyntheticActivity(start=BASE_START))
    write_fit(
        fit_dir,
        "2.fit",
        SyntheticActivity(start=BASE_START + timedelta(days=5), serial_number=3_900_001_235),
    )
    write_fit(
        fit_dir,
        "3.fit",
        SyntheticActivity(start=BASE_START + timedelta(days=10), serial_number=3_900_001_236),
    )
    provider = GarminFitProvider()

    rng = provider.get_historical_range(account)
    assert rng.start == BASE_START.date()
    assert rng.end == (BASE_START + timedelta(days=10)).date()

    full = provider.initial_import(account)
    assert len(full.source_activities) == 3
    assert len(full.activities) == 3
    assert len(full.payloads) == 3

    window = provider.initial_import(
        account,
        start=(BASE_START + timedelta(days=4)).date(),
        end=(BASE_START + timedelta(days=6)).date(),
    )
    assert [sa.start_time_utc for sa in window.source_activities] == [
        BASE_START + timedelta(days=5)
    ]


def test_import_result_payload_and_links_account(account, fit_dir):
    spec = SyntheticActivity()
    write_fit(fit_dir, "run.fit", spec)
    result = GarminFitProvider().initial_import(account)

    sa = result.source_activities[0]
    assert sa.source == "garmin_fit"
    assert sa.account_id == account.id
    assert sa.source_activity_id == f"{spec.serial_number}-20240310T073000Z"
    assert sa.device_name == "garmin fr255_music"
    assert sa.provenance and sa.provenance["parser_version"] == FitParser.VERSION
    assert sa.provenance["raw_sha256"]

    payload = result.payloads[sa.source_activity_id]
    assert payload.raw_content == build_fit(spec)
    assert payload.raw_kind == "fit"
    assert payload.device == {
        "manufacturer": "garmin",
        "model": "fr255_music",
        "serial_number": str(spec.serial_number),
    }
    assert payload.stream_rows and payload.intervals
    assert result.cursor == {"last_start_time_utc": spec.start.isoformat()}

    assert GarminFitProvider().download_activity_file(
        account, sa.source_activity_id
    ) == build_fit(spec)
    assert GarminFitProvider().download_activity_file(account, "missing") is None


def test_incremental_sync_uses_account_cursor(account, fit_dir):
    write_fit(fit_dir, "1.fit", SyntheticActivity(start=BASE_START))
    provider = GarminFitProvider()

    first = provider.incremental_sync(account)
    assert len(first.source_activities) == 1
    account.cursor_json = first.cursor

    nothing = provider.incremental_sync(account)
    assert nothing.source_activities == []
    assert nothing.cursor == first.cursor

    write_fit(
        fit_dir,
        "2.fit",
        SyntheticActivity(start=BASE_START + timedelta(days=1), serial_number=1),
    )
    second = provider.incremental_sync(account)
    assert [sa.source_activity_id for sa in second.source_activities] == ["1-20240311T073000Z"]
    assert second.cursor["last_start_time_utc"] == (BASE_START + timedelta(days=1)).isoformat()


