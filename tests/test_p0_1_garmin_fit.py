def test_orchestrator_persists_raw_device_activity_and_provenance(db, account, fit_dir):
    spec = SyntheticActivity()
    write_fit(fit_dir, "run.fit", spec)

    summary = IngestionOrchestrator(db).run(account, GarminFitProvider())
    db.commit()

    assert summary.created == 1 and summary.failed == 0 and summary.errors == []

    raw = db.query(RawFile).one()
    assert raw.source == "garmin_fit"
    assert raw.kind == "fit"
    assert RawStore().read_bytes(raw) == build_fit(spec)

    device = db.query(Device).one()
    assert device.serial_number == str(spec.serial_number)
    assert device.manufacturer == "garmin"
    assert account.device_id == device.id

    sa = db.query(SourceActivity).one()
    assert sa.account_id == account.id
    assert sa.device_id == device.id
    assert sa.fit_raw_file_id == raw.id
    assert sa.provenance["raw_file_id"] == str(raw.id)
    assert sa.provenance["device_id"] == str(device.id)
    assert sa.provenance["account_id"] == str(account.id)

    activity = db.query(Activity).one()
    assert sa.canonical_activity_id == activity.id
    assert activity.primary_source == "garmin_fit"
    assert float(activity.distance_m) == pytest.approx(spec.distance_m)
    assert activity.provenance["source"] == "garmin_fit"
    assert activity.provenance["raw_file_id"] == str(raw.id)

    link = db.query(ActivityLink).one()
    assert link.match_method == "primary"
    assert link.source_activity_id == sa.id

    stream_set = db.query(ActivityStreamSet).one()
    assert stream_set.source_activity_id == sa.id
    assert "garmin_fit" in stream_set.storage_path
    assert (settings.processed_root_path / stream_set.storage_path).exists()
    assert stream_set.sample_count == spec.duration_s // spec.sample_interval_s + 1
    assert db.query(ActivityInterval).count() == 1

    caps = db.query(MetricCapability).filter_by(source="garmin_fit").all()
    assert {c.metric for c in caps} >= {"heart_rate", "gps", "hrv"}

    assert account.health == "ok"
    assert account.auth_status == "not_required"
    assert account.last_success_at is not None
    assert account.cursor_json == {"last_start_time_utc": spec.start.isoformat()}


def test_orchestrator_reimport_is_idempotent(db, account, fit_dir):
    write_fit(fit_dir, "run.fit", SyntheticActivity())
    orchestrator = IngestionOrchestrator(db)

    first = orchestrator.run(account, GarminFitProvider())
    second = orchestrator.run(account, GarminFitProvider())
    db.commit()

    assert first.created == 1
    assert second.reimported == 1 and second.created == 0
    assert db.query(SourceActivity).count() == 1
    assert db.query(Activity).count() == 1
    assert db.query(RawFile).count() == 1
    assert db.query(Device).count() == 1


def test_orchestrator_auto_links_same_activity_from_another_source(db, athlete, account, fit_dir):
    spec = SyntheticActivity()
    existing_activity = Activity(
        athlete_id=athlete.id,
        start_time_utc=spec.start,
        sport="running",
        primary_source="source_a",
        duration_elapsed_s=spec.duration_s,
        distance_m=spec.distance_m,
    )
    db.add(
        SourcePriority(
            athlete_id=athlete.id, metric="activity", priority=["garmin_fit", "source_a"]
        )
    )
    db.add(existing_activity)
    db.flush()
    db.add(
        SourceActivity(
            athlete_id=athlete.id,
            source="source_a",
            source_activity_id="ext-1",
            canonical_activity_id=existing_activity.id,
            start_time_utc=existing_activity.start_time_utc,
            duration_elapsed_s=spec.duration_s,
            distance_m=spec.distance_m,
            status="linked",
        )
    )
    db.flush()

    write_fit(fit_dir, "run.fit", spec)
    summary = IngestionOrchestrator(db).run(account, GarminFitProvider())
    db.commit()

    assert summary.linked == 1 and summary.created == 0
    assert db.query(Activity).count() == 1
    garmin_sa = db.query(SourceActivity).filter_by(source="garmin_fit").one()
    assert garmin_sa.canonical_activity_id == existing_activity.id
    link = db.query(ActivityLink).filter_by(source_activity_id=garmin_sa.id).one()
    assert link.match_method == "dedupe_auto"
    assert link.evidence["decision"] == "AUTO_LINK"
    assert db.query(RawFile).count() == 1


def test_orchestrator_keeps_ambiguous_match_for_review(db, athlete, account, fit_dir):
    spec = SyntheticActivity()
    existing_activity = Activity(
        athlete_id=athlete.id,
        start_time_utc=spec.start,
        sport="running",
        primary_source="source_a",
        duration_elapsed_s=spec.duration_s * 0.98,
        distance_m=spec.distance_m * 0.98,
    )
    db.add(existing_activity)
    db.flush()
    db.add(
        SourceActivity(
            athlete_id=athlete.id,
            source="source_a",
            source_activity_id="ext-2",
            canonical_activity_id=existing_activity.id,
            start_time_utc=existing_activity.start_time_utc,
            duration_elapsed_s=spec.duration_s * 0.98,
            distance_m=spec.distance_m * 0.98,
            status="linked",
        )
    )
    db.flush()

    write_fit(fit_dir, "run.fit", spec)
    summary = IngestionOrchestrator(db).run(account, GarminFitProvider())
    db.commit()

    assert summary.reviewed == 1
    review = db.query(DedupeReview).one()
    assert review.status == "pending"
    assert review.candidates["existing_canonical_activity_id"] == str(existing_activity.id)
    assert "final_score" in review.candidates["scores"]
    assert db.query(Activity).count() == 2
    garmin = db.query(Activity).filter_by(primary_source="garmin_fit").one()
    assert "dedupe_review_pending" in (garmin.quality_flags or [])


