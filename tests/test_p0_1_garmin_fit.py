def test_authenticate_validates_import_dir(db, athlete, fit_dir):
    provider = GarminFitProvider()

    missing = AthleteSourceAccount(athlete_id=athlete.id, source="garmin_fit")
    assert provider.authenticate(missing)["status"] == "error"

    bad = AthleteSourceAccount(
        athlete_id=athlete.id,
        source="garmin_fit",
        auth_json={"import_dir": str(fit_dir / "nope")},
    )
    assert provider.authenticate(bad)["auth_status"] == "import_dir_not_found"

    write_fit(fit_dir, "a.fit", SyntheticActivity())
    ok = AthleteSourceAccount(
        athlete_id=athlete.id, source="garmin_fit", auth_json={"import_dir": str(fit_dir)}
    )
    result = provider.authenticate(ok)
    assert result["status"] == "ok"
    assert result["auth_status"] == "not_required"
    assert result["file_count"] == 1


