def test_parse_bytes_extracts_summary_device_and_streams():
    spec = SyntheticActivity()
    doc = FitParser(source="garmin_fit").parse_bytes(build_fit(spec))

    assert doc.start_time == spec.start
    assert doc.sport == "running"
    assert doc.duration_elapsed_s == pytest.approx(spec.duration_s)
    assert doc.distance_m == pytest.approx(spec.distance_m)
    assert doc.ascent_m == pytest.approx(spec.ascent_m)
    assert doc.avg_hr is not None and spec.hr_start <= doc.avg_hr <= spec.hr_end
    assert doc.device.manufacturer == "garmin"
    assert doc.device.serial_number == str(spec.serial_number)
    assert doc.natural_id() == f"{spec.serial_number}-20240310T073000Z"

    rows = doc.canonical_stream_rows()
    assert len(rows) == spec.duration_s // spec.sample_interval_s + 1
    assert {"t_s", "hr_bpm", "lat", "lon", "distance_m", "altitude_m"} <= set(rows[0])
    assert rows[0]["lat"] == pytest.approx(spec.lat, abs=1e-5)
    assert len(doc.laps) == 1 and len(doc.sessions) == 1


def test_parse_bytes_is_deterministic_and_content_addressed():
    content = build_fit(SyntheticActivity())
    parser = FitParser(source="garmin_fit")
    assert parser.parse_bytes(content).sha256 == parser.parse_bytes(content).sha256
    other = build_fit(SyntheticActivity(hr_start=100))
    assert parser.parse_bytes(content).sha256 != parser.parse_bytes(other).sha256


